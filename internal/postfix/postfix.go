func WriteVirtualMaps(domains []config.Domain) error {
	var mailbox []string
	for _, d := range domains {
		for _, acc := range d.Accounts {
			if acc.LocalUser == "" {
				continue
			}
			addr := fmt.Sprintf("%s@%s", acc.LocalPart, d.Name)
			mailbox = append(mailbox, fmt.Sprintf("%s    %s/", addr, acc.LocalUser))
		}
	}
	if err := os.WriteFile("/etc/postfix/vmailbox", []byte(strings.Join(mailbox, "\n")+"\n"), 0644); err != nil {
		return err
	}
	fmt.Println("[postfix] wrote vmailbox")
	return nil
}

// WriteSenderLogin writes the sender-login ownership map: each account address
// is owned by the SASL login of the same name (the full address). Postfix uses
// it with reject_sender_login_mismatch to keep one account from sending as
// another.
func WriteSenderLogin(domains []config.Domain) error {
	var lines []string
	for _, d := range domains {
		for _, acc := range d.Accounts {
			addr := acc.LocalPart + "@" + d.Name
			lines = append(lines, fmt.Sprintf("%s    %s", addr, addr))
		}
	}
	if err := os.WriteFile(SenderLoginFile, []byte(strings.Join(lines, "\n")+"\n"), 0644); err != nil {
		return err
	}
	fmt.Println("[postfix] wrote sender_login")
	return nil
}

func validateRelay(r *config.Relay) error {
	if r.Host == "" || r.Username == "" || r.Password == "" {
		return fmt.Errorf("requires host, username and password")
	}
	return nil
}

// writeSecret writes content to path owned root:postfix mode 0640, so the
// unprivileged smtp(8) client can read it while keeping the password off
// world-readable storage. It writes 0600 first so the file is never briefly
// group-readable before the chown narrows ownership.
func writeSecret(path, content string) error {
	if err := os.WriteFile(path, []byte(content), 0600); err != nil {
		return err
	}
	if err := util.Run("chown", "root:postfix", path); err != nil {
		return err
	}
	return os.Chmod(path, 0640)
}

// WriteRelay writes the relay map files from the config: RelayPasswordFile
// always, and RelaySenderFile when any per-domain/per-account relay is set.
// Caller should only invoke this when HasRelay(cfg) is true.
func WriteRelay(cfg *config.Config) error {
	entries := senderRelays(cfg)
	senderDependent := len(entries) > 0

	var passwd, sender []string

	// Per-domain / per-account overrides: keyed by envelope sender.
	for _, e := range entries {
		r := e.Relay
		if err := validateRelay(r); err != nil {
			return fmt.Errorf("relay for %s: %w", e.Key, err)
		}
		if r.EffectivePort() == 465 {
			return fmt.Errorf("relay for %s: port 465 (implicit TLS) is not supported "+
				"with per-domain/per-account relays; use 587 (STARTTLS)", e.Key)
		}
		sender = append(sender, fmt.Sprintf("%s    %s", e.Key, relayNexthop(r)))
		passwd = append(passwd, fmt.Sprintf("%s    %s:%s", e.Key, r.Username, r.Password))
	}

	// Global relay: the relayhost fallback, keyed by nexthop destination.
	if cfg.Relay != nil {
		r := cfg.Relay
		if err := validateRelay(r); err != nil {
			return fmt.Errorf("global relay: %w", err)
		}
		if senderDependent && r.EffectivePort() == 465 {
			return fmt.Errorf("global relay: port 465 (implicit TLS) is not supported " +
				"alongside per-domain/per-account relays; use 587 (STARTTLS)")
		}
		passwd = append(passwd, fmt.Sprintf("%s    %s:%s", relayNexthop(r), r.Username, r.Password))
	}

	if err := writeSecret(RelayPasswordFile, strings.Join(passwd, "\n")+"\n"); err != nil {
		return err
	}
	fmt.Println("[postfix] wrote relay sasl_passwd")

	if senderDependent {
		// sender_relay holds no secrets, so 0644 is fine.
		if err := os.WriteFile(RelaySenderFile, []byte(strings.Join(sender, "\n")+"\n"), 0644); err != nil {
			return err
		}
		fmt.Println("[postfix] wrote relay sender_relay")
	}
	return nil
}

func SetupMaildirs(domains []config.Domain) error {
	vmail, err := user.Lookup("vmail")
	if err != nil {
		return fmt.Errorf("lookup vmail user: %w", err)
	}
	uid, gid := util.ParseInt(vmail.Uid), util.ParseInt(vmail.Gid)

	seen := map[string]bool{}
	for _, d := range domains {
		for _, acc := range d.Accounts {
			if acc.LocalUser == "" || seen[acc.LocalUser] {
				continue
			}
			seen[acc.LocalUser] = true
			base := fmt.Sprintf("/var/mail/%s", acc.LocalUser)
			if fi, err := os.Stat(base); err == nil && !fi.IsDir() {
				if err := os.Remove(base); err != nil {
					return fmt.Errorf("remove stale mbox %s: %w", base, err)
				}
			}
			for _, sub := range []string{"cur", "new", "tmp"} {
				dir := fmt.Sprintf("/var/mail/%s/%s", acc.LocalUser, sub)
				if err := os.MkdirAll(dir, 0700); err != nil {
					return fmt.Errorf("mkdir %s: %w", dir, err)
				}
				if err := os.Chown(dir, uid, gid); err != nil {
					return fmt.Errorf("chown %s: %w", dir, err)
				}
			}
			if err := os.Chown(base, uid, gid); err != nil {
				return fmt.Errorf("chown %s: %w", base, err)
			}
			fmt.Printf("[postfix] maildir ready: %s\n", base)
		}
	}
	return nil
}
